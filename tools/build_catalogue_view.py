"""Build the English upstream catalogue view from the frozen public JSON.

Python standard library only. The data tree is read-only. --check compares
the generated bytes with the existing page and writes nothing.
"""
from collections import Counter
from pathlib import Path
import argparse
import hashlib
import json
import os


def digest(blob):
    return hashlib.sha256(blob).hexdigest()


def generate(root):
    version = root / "data/2026-11-02"
    catalog_path = version / "catalog.json"
    manifest = json.loads((root / "data/manifest.json").read_text(encoding="utf-8"))
    blob = catalog_path.read_bytes()
    assert digest(blob) == manifest["files"]["2026-11-02/catalog.json"], "Frozen catalogue bytes differ"
    catalog = json.loads(blob.decode("utf-8"))
    rows = catalog["integrals"]
    assert len(rows) == len({row["stable_id"] for row in rows}) == 163
    destination = root / "docs/upstream/catalogue.md"

    def relative(path):
        resolved = (version / path).resolve()
        assert resolved.is_relative_to(version.resolve()), path
        assert resolved.is_file(), path
        return os.path.relpath(resolved, destination.parent).replace("\\", "/")

    counts = Counter(row["loop_order"] for row in rows)
    assert dict(counts) == {1: 2, 2: 12, 3: 149}
    prepared_orbits = sum(bool(row["prepared_inputs"]) for row in rows)
    prepared_occurrences = sum(len(row["prepared_inputs"]) for row in rows)
    lines = [
        "# Integral input catalogue",
        "",
        "This index follows the frozen **2026-11-02** upstream data catalogue: "
        "163 source orbits across 13 families, with original raw C/J available for every entry. "
        "The one-, two- and three-loop catalogues contain 2, 12 and 149 orbits, respectively.",
        "",
        f"Separate existing prepared payloads are available for {prepared_orbits} orbits, "
        f"in {prepared_occurrences} representation/version occurrences. The prepared count below "
        "counts available alternatives for one orbit; it is not a multiplicity or a number "
        "of independent calculations. A zero count means no separate prepared payload "
        "was included in this batch, while the raw input remains available.",
        "",
        "A source orbit is a canonical representative, possibly containing an effective "
        "self-energy or vertex operator. The count is not a new microscopic QCD graph "
        "completeness claim. Four-leg source rows remain separate here and also map to "
        "their joint objects; they must not be counted twice in a color sum.",
        "",
        "The raw C/J link opens the complete byte-preserved native family package. "
        "The per-integral input JSON identifies its exact orbit/field pointers and hashes; "
        "the English page explains the domain, normalization and available alternatives. "
        "These are input definitions. This index exports no Laurent coefficient or new "
        "integral derivation, and it does not reinterpret historical status labels.",
        "",
        "- [Data scope and conventions](../../data/2026-11-02/README.md)",
        "- [Machine catalogue](../../data/2026-11-02/catalog.json)",
        "- [Coverage and explicit input-format gaps](../../data/2026-11-02/coverage.json)",
        "- [Four-leg joint-source map](../../data/2026-11-02/four-leg-joint-map.json)",
        "",
    ]
    labels = {1: "One loop", 2: "Two loops", 3: "Three loops"}
    for loop in (1, 2, 3):
        selected = sorted((row for row in rows if row["loop_order"] == loop),
                          key=lambda row: (row["family"], row["orbit_id"]))
        lines += [f"## {labels[loop]}: {len(selected)} source orbits", "",
                  "| Integral ID | Family | Original C/J | Prepared alternatives | English entry | Machine input |",
                  "| --- | --- | --- | ---: | --- | --- |"]
        for row in selected:
            raw = row.get("raw_C")
            available = bool(raw and row.get("raw_kernels"))
            assert available, row["orbit_id"]
            raw_link = f"[available]({relative(raw['path'])})"
            page = relative(row["readme_path"])
            inp = relative(row["input_path"])
            lines.append(f"| `{row['orbit_id']}` | `{row['family']}` | {raw_link} | "
                         f"{len(row['prepared_inputs'])} | [Read]({page}) | [JSON]({inp}) |")
        lines.append("")
    lines += [
        "## Rebuild this reading view", "",
        "From the repository root:", "",
        "```text",
        "python tools/build_catalogue_view.py",
        "python tools/build_catalogue_view.py --check",
        "```", "",
        "The builder uses only the frozen catalogue and the Python standard library. "
        "It verifies the catalogue's manifest hash before generating this page and "
        "never writes to data/. The --check command is entirely read-only. "
        "No timestamps, absolute workspace paths or platform-dependent line endings "
        "enter this generated view.", "",
    ]
    return destination, ("\n".join(lines)).encode("utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    destination, output = generate(root)
    if args.check:
        assert destination.read_bytes() == output, "Catalogue view is stale; rebuild it"
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(output)
    print(json.dumps({"status": "passed", "read_only": args.check,
                      "path": destination.relative_to(root).as_posix(),
                      "bytes": len(output), "sha256": digest(output), "orbits": 163}))
