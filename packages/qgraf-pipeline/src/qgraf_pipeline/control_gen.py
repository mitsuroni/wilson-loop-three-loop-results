"""Generate QGRAF control file for n-loop Wilson loop."""
from __future__ import annotations

from pathlib import Path


def _get_data_dir() -> Path:
    return Path(__file__).resolve().parent / "data"


def generate_control(n: int, output_dir: Path) -> Path:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    model_path = _get_data_dir() / "qcd_wl.mod"
    style_path = _get_data_dir() / "style.sty"

    content = (
        f"# QGRAF control file for {n}-loop Wilson loop\n"
        f"# Auto-generated by qgraf-pipeline\n\n"
        f"output = 'wilsonloop_{n}loop.out'\n"
        f"style = '{style_path}'\n"
        f"model = '{model_path}'\n\n"
        f"in = phi1, phi2, phi3, phi4\n"
        f"out = phi1, phi2, phi3, phi4\n\n"
        f"vsum = {n}\n\n"
        f"true = qcdloops\n"
    )
    control_path = output_dir / f"control_{n}loop.dat"
    control_path.write_text(content)
    return control_path
