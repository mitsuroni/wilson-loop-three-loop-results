Print["单一算子项：C_t = -z, v_p = v_3, d_p = (+1,-1,0,0), v_q = v_4, d_q = (0,0,+1,-1)"];

(* ========================================================================= *)
(* 计算 F^(p), G^(q), H^(pq)                                                 *)
(* ========================================================================= *)

(* F^(p) = v_3·(∂₁-∂₂)B_5 = F_1^(3) - F_2^(3) *)
(* F_i^(3) = -2α_i Σ_{j≠i} α_j c_{ij} v_3·(X_i - X_j) *)

(* F_1^(3) = -2α_1[α_2 c_{12} v_3·(X_1-X_2) + α_3 c_{13} v_3·(X_1-X_3) + α_4 c_{14} v_3·(X_1-X_4)] *)
(* c_{12} = α_3+α_4+α_5, v_3·(X_1-X_2) = 0 *)
(* c_{13} = α_5, v_3·(X_1-X_3) = -s3*z *)
(* c_{14} = α_5, v_3·(X_1-X_4) = -s4*z *)
(* F_1^(3) = -2α_1[0 + α_3 α_5 (-s3*z) + α_4 α_5 (-s4*z)] = 2α_1 α_5 z [α_3 s3 + α_4 s4] *)

(* F_2^(3) = -2α_2[α_1 c_{12} v_3·(X_2-X_1) + α_3 c_{23} v_3·(X_2-X_3) + α_4 c_{24} v_3·(X_2-X_4)] *)
(* v_3·(X_2-X_1) = 0, v_3·(X_2-X_3) = -s3*z, v_3·(X_2-X_4) = -s4*z *)
(* F_2^(3) = 2α_2 α_5 z [α_3 s3 + α_4 s4] *)

(* F^(p) = 2α_5 z (α_1 - α_2)(α_3 s_{4,1} + α_4 s_{4,2}) *)

(* F^(q) = v_4·(∂_3-∂_4)B_5 = F_3^(4) - F_4^(4) *)
(* F_3^(4) = -2α_3[α_1 c_{13} v_4·(X_3-X_1) + α_2 c_{23} v_4·(X_3-X_2) + α_4 c_{34} v_4·(X_3-X_4)] *)
(* c_{13} = α_5, v_4·(X_3-X_1) = (1-s1)z *)
(* c_{23} = α_5, v_4·(X_3-X_2) = (1-s2)z *)
(* c_{34} = α_1+α_2+α_5, v_4·(X_3-X_4) = 0 *)
(* F_3^(4) = -2α_3 α_5 z [α_1(1-s1) + α_2(1-s2)] *)

