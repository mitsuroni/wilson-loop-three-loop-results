(* G4b = -v_ad * (2v_b·ℓ₁+v_b·ℓ₂)(v_c·ℓ₃+2v_c·ℓ₄) *)
(* G4c = -v_bc * (v_a·ℓ₁+2v_a·ℓ₂)(2v_d·ℓ₃+v_d·ℓ₄) *)
(* G4d = v_bd * (v_a·ℓ₁+2v_a·ℓ₂)(v_c·ℓ₃+2v_c·ℓ₄) *)

(* S 道：v_a=v_b=v_3, v_c=v_d=v_4, v_ac=v_ad=v_bc=v_bd=z *)
(* A1 = 2v_3·ℓ₁ + v_3·ℓ₂, A2 = v_3·ℓ₁ + 2v_3·ℓ₂ *)
(* B1 = 2v_4·ℓ₃ + v_4·ℓ₄, B2 = v_4·ℓ₃ + 2v_4·ℓ₄ *)

(* L_S = z(A1*B1 - A1*B2 - A2*B1 + A2*B2) = z(A1-A2)(B1-B2) *)
(*     = z (v_3·ℓ₁ - v_3·ℓ₂)(v_4·ℓ₃ - v_4·ℓ₄) *)
(*     = z v_3·(ℓ₁-ℓ₂) v_4·(ℓ₃-ℓ₄) *)

(* ℓ→i∂_X: *)
(* O_S = -z (v_3·(∂₁-∂₂)) (v_4·(∂₃-∂₄)) *)

