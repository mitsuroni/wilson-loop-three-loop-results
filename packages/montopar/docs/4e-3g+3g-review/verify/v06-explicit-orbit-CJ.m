(* v_3·(X1-X2) = v_3·(s1-s2)v_3 = 0 *)
(* v_3·(X1-X3) = v_3·(v1+v2+s1*v3 - v1-v2-v3-s3*v4) = v_3·(-v3-s3*v4) = -s3*z *)
(* v_3·(X1-X4) = -s4*z *)
(* v_3·(X2-X3) = -s3*z *)
(* v_3·(X2-X4) = -s4*z *)

(* v_4·(X3-X4) = v_4·(s3-s4)v_4 = 0 *)
(* v_4·(X3-X1) = v_4·(v1+v2+v3+s3*v4 - v1-v2-s1*v3) = v_4·(v3-s1*v3+s3*v4) = (1-s1)*z *)
(* v_4·(X3-X2) = (1-s2)*z *)
(* v_4·(X4-X1) = (1-s1)*z *)
(* v_4·(X4-X2) = (1-s2)*z *)

(* ========================================================================= *)
(* 计算 B_5                                                                  *)
(* ========================================================================= *)

(* B_5 = Σ_{i<j} α_i α_j c_{ij} Δ_{ij} *)
(* Δ_{ij} = -(X_i - X_j)^2 *)
(* c_{ij}: 见 §8 Step 2 *)

(* 先计算 Δ_{ij} *)
(* Δ_{12} = -(X1-X2)^2 = -(s1-s2)^2 v_3^2 = 0 *)
(* Δ_{34} = -(X3-X4)^2 = -(s3-s4)^2 v_4^2 = 0 *)
(* Δ_{13} = -(X1-X3)^2 *)
(* X1 - X3 = v1+v2+s1*v3 - v1-v2-v3-s3*v4 = (s1-1)*v3 - s3*v4 *)
(* Δ_{13} = -[(s1-1)^2 v_3^2 + s3^2 v_4^2 - 2(s1-1)s3 v_3·v_4] = 2(1-s1)s3*z *)
(* Δ_{14} = 2(1-s1)s4*z *)
(* Δ_{23} = 2(1-s2)s3*z *)
(* Δ_{24} = 2(1-s2)s4*z *)

(* 所以 B_5 = α_5 [α_1 α_3 Δ_{13} + α_1 α_4 Δ_{14} + α_2 α_3 Δ_{23} + α_2 α_4 Δ_{24}] *)

(* B_5 = 2 α_5 z [α_1 α_3 (1-s1)s3 + α_1 α_4 (1-s1)s4 + α_2 α_3 (1-s2)s3 + α_2 α_4 (1-s2)s4] *)
(*     = 2 α_5 z [α_1(1-s1) + α_2(1-s2)] [α_3 s3 + α_4 s4] *)

